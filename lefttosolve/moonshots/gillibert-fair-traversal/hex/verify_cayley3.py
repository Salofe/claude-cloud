#!/usr/bin/env python3
"""Independent check of a PASS certificate for a cubic graph whose edge classes are three perfect matchings.
usage: verify_cayley3.py labelsfile certfile
1. the labelling (taken from the LABELS line) is checked to consist of three perfect matchings a, b, c whose
   permutation group <a,b,c> acts regularly on the vertices; then left multiplications are automorphisms that
   preserve each class and act transitively on it, so each class lies inside one orbit of Aut(G);
2. every path of the certificate is checked to be a Hamiltonian path of the graph given by the LABELS line;
3. the class-size vector is checked, with exact rational arithmetic, to be a nonnegative combination of the
   count vectors of the paths."""
import sys
from fractions import Fraction
from collections import deque
lab_line = [l for l in open(sys.argv[1]) if l.startswith('LABELS')][0]
head, info, body = lab_line.split('|')
kv = dict(x.split('=') for x in info.split()); n, deg, K = int(kv['n']), int(kv['deg']), int(kv['K'])
toks = body.split(); assert deg == 3 and K == 3 and len(toks) == 3 * n
nb = [[None]*3 for _ in range(n)]
for i, t in enumerate(toks):
    u, l = t.split(':'); v = i // 3
    assert nb[v][int(l)] is None; nb[v][int(l)] = int(u)
for v in range(n):
    for c in range(3):
        u = nb[v][c]; assert u is not None and u != v and nb[u][c] == v
    assert len(set(nb[v])) == 3
perms = [tuple(nb[v][c] for v in range(n)) for c in range(3)]
def mul(p, q): return tuple(q[i] for i in p)
e = tuple(range(n)); elems = {0: e}; dq = deque([0])
while dq:
    v = dq.popleft(); p = elems[v]
    for g in perms:
        q = mul(p, g); w = q[0]
        if w not in elems: elems[w] = q; dq.append(w)
        else: assert elems[w] == q, 'the group generated by the three matchings is not regular'
assert len(elems) == n
print('labelling ok: three perfect matchings generating a regular group of order', n)
adjset = [set(x) for x in nb]
cert = [l for l in open(sys.argv[2]) if l.startswith('CERT')][0]
parts = cert.split('|')
cadj = list(map(int, parts[3].split()[1:]))
assert len(cadj) == 3*n and all(set(cadj[3*v:3*v+3]) == adjset[v] for v in range(n)), 'certificate graph differs'
ptoks = parts[4].split(); npaths = int(ptoks[1]); rest = ' '.join(ptoks[2:]).split(';')[1:]
assert len(rest) == npaths
vecs = []
for r in rest:
    P = list(map(int, r.split()))
    assert len(P) == n and sorted(P) == list(range(n)) and all(P[i+1] in adjset[P[i]] for i in range(n-1))
    c = [0, 0, 0]
    for i in range(n-1): c[nb[P[i]].index(P[i+1])] += 1
    vecs.append(c)
sizes = [n // 2] * 3
print('paths ok:', npaths, 'count vectors', vecs)
# exact solve: find lambda >= 0 with sum lambda_j vec_j = sizes (npaths <= 3: solve the linear system by Cramer / elimination)
import itertools
def solve(A, b):
    m = len(A); k = len(A[0])
    M = [[Fraction(A[i][j]) for j in range(k)] + [Fraction(b[i])] for i in range(m)]
    piv = []; r = 0
    for c in range(k):
        pr = next((i for i in range(r, m) if M[i][c] != 0), None)
        if pr is None: continue
        M[r], M[pr] = M[pr], M[r]
        M[r] = [x / M[r][c] for x in M[r]]
        for i in range(m):
            if i != r and M[i][c] != 0: M[i] = [x - M[i][c]*y for x, y in zip(M[i], M[r])]
        piv.append(c); r += 1
    if any(all(x == 0 for x in row[:-1]) and row[-1] != 0 for row in M): return None
    if len(piv) < k: return None
    return [M[i][-1] for i in range(k)]
A = [[vecs[j][i] for j in range(npaths)] for i in range(3)]
lam = solve(A, sizes)
assert lam is not None and all(x >= 0 for x in lam), 'not in the cone'
assert all(sum(lam[j]*vecs[j][i] for j in range(npaths)) == sizes[i] for i in range(3))
print('exact coefficients', [str(x) for x in lam], '-> VERIFIED: the size vector is in the cone')
